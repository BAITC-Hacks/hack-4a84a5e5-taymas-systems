from pydantic import BaseModel

from app.models import CARD_FIELDS, Question

QUESTIONS_SYSTEM = (
    "Ты помогаешь представителю бизнеса дополнить черновик задачи для студенческой команды.\n"
    "Правила:\n"
    f"- Задай от 3 до 6 уточняющих вопросов, каждый закрывает ровно одно поле карточки. "
    f"Поле — строго одно из: {', '.join(CARD_FIELDS)}.\n"
    "- Вопрос должен опираться на конкретные детали черновика, а не быть общим шаблоном.\n"
    "- Никогда не предлагай готовых вариантов ответа и не добавляй фактов, которых нет "
    "в черновике или в списке пробелов ниже.\n"
    "- Не спрашивай про персональные данные конкретных людей (студентов, сотрудников).\n"
    "- Пиши только на русском языке."
)


class QuestionsResponse(BaseModel):
    """Формат выхода: JSON со списком вопросов для generate_questions."""

    questions: list[Question]


def build_questions_user_prompt(
    draft_text: str, industry: str, gaps: list[tuple[str, int, int]]
) -> str:
    """Формат входа: черновик, отрасль и показатели рейтинга с недобором.

    gaps — тройки (подпись показателя, вес, начислено), отсортированы по убыванию недобора.
    """
    gap_lines = "\n".join(
        f"- {label}: начислено {awarded} из {weight} баллов" for label, weight, awarded in gaps
    ) or "- пробелов по рейтингу нет, но уточняющие вопросы всё равно нужны"
    return (
        f"Отрасль: {industry}\n"
        f"Черновик задачи от бизнеса:\n{draft_text}\n\n"
        f"Показатели рейтинга с недобором (более важные — выше):\n{gap_lines}"
    )
