class QuestionsResponse(BaseModel):
    """Формат выхода: JSON со списком вопросов для generate_questions."""

    questions: list[Question]


def build_questions_user_prompt(
    draft_text: str, industry: str, gaps: list[tuple[str, int, int]]
) -> str:
    """Формат входа: черновик, отрасль и показатели рейтинга с недобором.

    gaps — тройки (подпись показателя, вес, начислено), отсортированы по убыванию недобора.
    """
    gap_lines = "\n".join(
        f"- {label}: начислено {awarded} из {weight} баллов" for label, weight, awarded in gaps
    ) or "- пробелов по рейтингу нет, но уточняющие вопросы всё равно нужны"
    return (
        f"Отрасль: {industry}\n"
        f"Черновик задачи от бизнеса:\n{draft_text}\n\n"
        f"Показатели рейтинга с недобором (более важные — выше):\n{gap_lines}"
    )


